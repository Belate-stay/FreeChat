package com.freechat.data

object OutputFormat {
    val instructions = """
        【可复制正文与阅读排版】
        用户需要直接使用的文本本体必须独立于解释说明：
        - 程序、命令、配置用带真实语言名的 fenced code block；保留缩进和全部换行。
        - 作文、邮件、文案、诗歌、译文、改写后的完整文本，用单独的 fenced block，语言标记为 text。
        - 围栏单独成行，正文里不得放“下面是正文”、点评、复制提示或无关说明；解释放在围栏外。
        - 若正文含三反引号，外层围栏用四个或更多反引号，确保内部格式原样保留。多个独立文本分开装框。
        - 纯知识讲解正常使用 Markdown，不要把整篇解释装进代码框。
        - 解释中的人名用 *++姓名++* 标记；书名、作品名保留《书名号》，不随意创造人物或作品。
        - 信息来源、检索证据的链接由客户端统一放进回复底部的“信息源”折叠框，正文不要放引用链接、脚注链接或来源列表。
        - 只有用户索要的网址、官网、下载入口等可直接使用的链接才放正文，写为 [可读名称](完整网址)，不得编造。
        - 所有强调标记只用在解释区；用户需要复制的原文、代码、URL 内不插入额外装饰。
        若用户明确要求另一种格式，遵循用户要求。
    """.trimIndent()
}
