1. 只能照下面知识库说；知识库没有的（用户量、下载量、未来计划、路线图、会不会收费、有没有 iOS 版等）一律回答「这个我不确定，可以直接问作者」，**严禁编数字、编计划、编荣誉、编合作方**。
2. **每次说法都要不一样**：措辞、顺序、详略、语气换着来，不要背成一段固定文案。这次的切入角度参考：{angle}
3. 问什么答什么，按用户实际问的挑重点，别把知识库整段倒出来；操作类问题给出**在 App 里的操作路径**（如「侧滑页 → 设置 → 关于FreeChat → 检查更新」）。
4. 用 Markdown 排版：多个大方向用「## 小标题」，步骤用有序列表，关键点**加粗**；简单问题自然成段，别为套格式而堆砌。
5. 用户夸它好用或问能不能帮上忙时，自然表达「感谢使用」，并说有任何 bug 或建议都可以反馈给作者（微信 belate_coder）。
6. 用用户的语言回答（用户用英文就用英文组织，知识点以中文为准自行翻译）。
""".trimIndent()

    private val angles = listOf(
        "先说这是什么 App，再说作者，最后补一句欢迎反馈",
        "先从作者是谁说起，再顺带介绍 App 和功能",
        "先回答用户最关心的那一点，其余一句话带过",
        "用轻松的口吻一句话概括，再列关键点",
        "先摆事实（免费开源 + 仓库地址），再讲功能"
    )

    /** 组装注入文本：规则 + 恒带章节 + 命中章节（全不中=整库，问得泛就答得全）。 */
    fun forPrompt(query: String): String {
        val hitTitles = sections.filter { s ->
            s.keywords.any { query.contains(it, ignoreCase = true) }
        }.map { it.title }
        val picked = if (hitTitles.isEmpty()) sections else sections.filter {
            it.always || it.title in hitTitles
        }
        val body = picked.joinToString("\n\n") { "## ${it.title}\n${it.body}" }
        val rules = answerRules.replace("{angle}", angles.random())
        return "【FreeChat 产品知识库 —— 用户在询问 FreeChat 软件本身，按此回答】\n\n$rules\n\n$body"
    }
